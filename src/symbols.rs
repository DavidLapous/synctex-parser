//! Static LaTeX math command classification and Unicode glyph canonicalization.

use unicode_normalization::UnicodeNormalization;

pub(crate) fn canonical(value: char) -> impl Iterator<Item = char> {
    let preserved = match value {
        'ϑ' | '\u{1D6DD}' | '\u{1D717}' | '\u{1D751}' | '\u{1D78B}' | '\u{1D7C5}' => Some('ϑ'),
        'ϰ' | '\u{1D6DE}' | '\u{1D718}' | '\u{1D752}' | '\u{1D78C}' | '\u{1D7C6}' => Some('ϰ'),
        'ϖ' | '\u{1D6E1}' | '\u{1D71B}' | '\u{1D755}' | '\u{1D78F}' | '\u{1D7C9}' => Some('ϖ'),
        'ϱ' | '\u{1D6E0}' | '\u{1D71A}' | '\u{1D754}' | '\u{1D78E}' | '\u{1D7C8}' => Some('ϱ'),
        _ => None,
    };
    // Normalize typographic/operator codepoint variants that share a TeX glyph.
    // Note: \epsilon/\varepsilon (ϵ/ε) and \phi/\varphi (ϕ/φ) intentionally fold
    // because Adobe Glyph List and TeX-cmmi10-builtin-0 swap phi/phi1.
    let mapped = match value {
        'ϵ' => 'ε',
        'ϕ' => 'φ',
        '−' => '-',
        '∗' => '*',
        '∙' => '•',
        '·' => '⋅',
        '⋯' => '…',
        '∆' => 'Δ',
        '▵' => '△',
        '▿' => '▽',
        '▴' => '▲',
        '▾' => '▼',
        '▸' => '▶',
        '◂' => '◀',
        '▹' => '▷',
        '◃' => '◁',
        '▫' | '◻' => '□',
        '▪' | '◼' => '■',
        '◯' => '○',
        '∊' => '∈',
        '∍' => '∋',
        '∼' => '~',
        '∖' => '\\',
        '〈' | '〈' => '⟨',
        '〉' | '〉' => '⟩',
        '⦗' => '⟮',
        '⦘' => '⟯',
        '⩽' => '≤',
        '⩾' => '≥',
        '⪙' => '⪕',
        '⪚' => '⪖',
        '∣' => '|',
        '∥' => '‖',
        '⟸' => '⇐',
        '⟹' => '⇒',
        '⟺' => '⇔',
        '⋃' => '∪',
        '⋂' => '∩',
        '⋁' => '∨',
        '⋀' => '∧',
        '⨀' => '⊙',
        '⨁' => '⊕',
        '⨂' => '⊗',
        '⨄' => '⊎',
        '⨅' => '⊓',
        '⨆' => '⊔',
        _ => value,
    };
    let (first, second) = match value {
        '≔' => (':', Some('=')),
        '≕' => ('=', Some(':')),
        _ => (mapped, None),
    };
    std::iter::once(first)
        .chain(second)
        .nfkc()
        .map(move |c| preserved.unwrap_or(c))
}

